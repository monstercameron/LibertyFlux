//! What is lifted from the two task shapes of this section, and what each
//! proof leaves out.
//!
//! One row per verified 32-bit routine lifted here. `Proven` means the
//! routine is restated on its owning type and the differential test crate
//! `lf-taskshapediff` ran it against its verified rewrite on the same
//! generated inputs, comparing results and every effect, with a
//! deliberately wrong lift caught alongside. The sections of the wider
//! `ped_task` family are in [`super::registry`].

use super::registry::State;

/// One verified routine's row in this section.
#[derive(Debug, Clone, Copy)]
pub struct Row {
    /// Owning structure short name.
    pub class: &'static str,
    /// Routine name in the 32-bit form.
    pub method: &'static str,
    /// Lift state.
    pub state: State,
    /// What the lift narrows away. Empty means the proof compares everything
    /// the rewrite does.
    pub narrows: &'static [&'static str],
}

