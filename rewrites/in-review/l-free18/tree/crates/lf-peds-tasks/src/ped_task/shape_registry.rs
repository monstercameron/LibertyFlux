//! What is lifted from the two task shapes of this section, and what each
//! proof leaves out.
//!
//! One row per verified 32-bit routine lifted here. `Proven` means the
//! routine is restated on its owning type and the differential test crate
//! `lf-taskshapediff` ran it against its verified rewrite on the same
//! generated inputs, comparing results and every effect, with a
//! deliberately wrong lift caught alongside. The sections of the wider
//! `ped_task` family are in [`super::registry`].

use super::registry::State;

/// One verified routine's row in this section.
#[derive(Debug, Clone, Copy)]
pub struct Row {
    /// Owning structure short name.
    pub class: &'static str,
    /// Routine name in the 32-bit form.
    pub method: &'static str,
    /// Lift state.
    pub state: State,
    /// What the lift narrows away. Empty means the proof compares everything
    /// the rewrite does.
    pub narrows: &'static [&'static str],
}

/// The rows of this section, grouped by structure.
pub const ROWS: &[Row] = &[
    // PredicateTask: two read-only predicates on the task object. Both
    // routines take the object alone and write nothing.
    Row {
        class: "PredicateTask",
        method: "enabled_positive_count",
        state: State::Proven,
        narrows: &[
            "the object is planted as a generated byte block; the proof compares the block after the call, which must be unchanged",
            "the unsigned enable compare and the signed count compare are both exercised over generated values, including the negative and zero counts",
        ],
    },
    Row {
        class: "PredicateTask",
        method: "resource_tag",
        state: State::Proven,
        narrows: &[
            "the resource is a second generated block planted at the address the task holds; the lift reads its tag word through the Option the test decodes from that block",
            "the resource is read only when the flag bit is clear and the kind reaches the minimum, as the rewrite's branches do; the proof compares the block after the call, which must be unchanged",
            "the words of the task outside the five the predicates read are not modelled and are left as generated",
        ],
    },
    // TaskStateBlock: the reset that clears the block and marks each
    // record's handle words invalid.
    Row {
        class: "TaskStateBlock",
        method: "reset",
        state: State::Proven,
        narrows: &[
            "the original stores its words in a scattered order with the header last; the lift states the final contents, which are the only observable effect (the proof compares all seventy-three words)",
            "the routine returns no value; none is compared, and the original's return register is not modelled",
            "the block is a generated word array in the proof; its address is not modelled",
        ],
    },
];

/// Counts of (proven, lifted-but-unproven, missing) rows in this section.
#[must_use]
pub fn counts() -> (usize, usize, usize) {
    let mut proven = 0;
    let mut lifted = 0;
    let mut missing = 0;
    for row in ROWS {
        match row.state {
            State::Proven => proven += 1,
            State::Lifted => lifted += 1,
            State::Missing => missing += 1,
        }
    }
    (proven, lifted, missing)
}
