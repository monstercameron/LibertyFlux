//! Differential test of the lifted task-id flag-bit read against the verified
//! rewrites of its family.
//!
//! Each rewrite reads a signed 16-bit task id from the record, follows a
//! pointer table entry for that id to an object, reads the object's flags word
//! and returns one bit of it. The lifted method is `TaskFlagBit::bit_of_entry`
//! in `lf-core`; the caller supplies the object for each id, and the test
//! supplies the same objects to the rewrite through the table words.
//!
//! For each instance, CASES cases are built: eight objects with generated
//! bytes, a table entry for each id from minus two to five pointing at its
//! object, and a record with a generated id in that range. The rewrite is
//! called with the record's address; the lifted method runs on the same bytes.
//! The results must match, and the record and the objects must be unchanged
//! afterwards, since the rewrite only reads them.
//!
//! Wrong versions, each of which every instance must catch: the flags word read
//! four bytes further on, the bit index one higher, and the bit returned
//! without masking to one bit.

#![cfg(target_arch = "x86")]

#[path = "support/instances_gen.rs"]
mod instances;

use std::sync::Mutex;

use instances::{INSTANCES, Instance};
use lf_core::object_rows::read_word;
use lf_core::task_flags::{FLAGS_OFFSET, ID_OFFSET, TASK_FLAG_BITS, TaskFlagBit, read_id};
use lf_taskflagdiff::rt::{SLOT_VAS, plant};

/// Generated cases per instance.
const CASES: u32 = 1000;

/// Bytes in one generated record. The id sits at its offset and the record is
/// only read.
const RECORD_BYTES: usize = 0x40;

/// Bytes in one generated object. The flags word, and the word four bytes on
/// that a wrong version reads, both fit.
const OBJECT_BYTES: usize = FLAGS_OFFSET + 8;

/// Smallest task id the generated records use; the table covers eight ids.
const FIRST_ID: i16 = -2;

/// One lock across the whole test program: the rewrites share the table.
static LOCK: Mutex<()> = Mutex::new(());

/// A deterministic generator (xorshift64), seeded per instance.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.0 = x;
        x
    }

    fn word(&mut self) -> u32 {
        self.next() as u32
    }

    /// Fills `bytes` with generated bytes, eight at a time.
    fn fill(&mut self, bytes: &mut [u8]) {
        for chunk in bytes.chunks_mut(8) {
            let word = self.next().to_le_bytes();
            chunk.copy_from_slice(&word[..chunk.len()]);
        }
    }
}

/// A candidate: the same contract as the lifted method, given the record and
/// the objects, one per table entry in id order.
type Candidate = fn(u32, &[u8], &[Vec<u8>]) -> u32;

/// The object the table names for `id`, for the test's objects.
fn object_for(objects: &[Vec<u8>], id: i16) -> &[u8] {
    &objects[usize::try_from(i32::from(id) - i32::from(FIRST_ID)).expect("test bug: id below the table")]
}

fn lifted(bit: u32, record: &[u8], objects: &[Vec<u8>]) -> u32 {
    TaskFlagBit::new(bit).bit_of_entry(record, |id| object_for(objects, id))
}

fn wrong_flags_offset(bit: u32, record: &[u8], objects: &[Vec<u8>]) -> u32 {
    let object = object_for(objects, read_id(record));
    (read_word(object, FLAGS_OFFSET + 4) >> bit) & 1
}

fn wrong_bit_one_higher(bit: u32, record: &[u8], objects: &[Vec<u8>]) -> u32 {
    TaskFlagBit::new(bit + 1).bit_of_entry(record, |id| object_for(objects, id))
}

fn wrong_unmasked(bit: u32, record: &[u8], objects: &[Vec<u8>]) -> u32 {
    let object = object_for(objects, read_id(record));
    read_word(object, FLAGS_OFFSET) >> bit
}

/// The first mismatch of a candidate against the instance's rewrite, if any.
fn first_mismatch(instance: &Instance, candidate: Candidate, seed: u64) -> Option<String> {
    let mut rng = Rng(seed);
    for case in 0..CASES {
        let mut objects: Vec<Vec<u8>> = (0..SLOT_VAS.len()).map(|_| vec![0u8; OBJECT_BYTES]).collect();
        for object in objects.iter_mut() {
            rng.fill(object);
        }
        for (slot, object) in objects.iter().enumerate() {
            plant(SLOT_VAS[slot], object.as_ptr() as usize as u32);
        }
        let mut record = vec![0u8; RECORD_BYTES];
        rng.fill(&mut record);
        let id = FIRST_ID + (rng.word() % SLOT_VAS.len() as u32) as i16;
        record[ID_OFFSET..ID_OFFSET + 2].copy_from_slice(&id.to_le_bytes());

        let before_record = record.clone();
        let before_objects = objects.clone();
        let returned = (instance.call)(record.as_ptr() as usize as u32);
        if record != before_record || objects != before_objects {
            return Some(format!(
                "{} case {}: the rewrite changed the record or an object, which it must only read",
                instance.address, case
            ));
        }
        let expected = candidate(instance.bit, &record, &objects);
        if returned != expected {
            return Some(format!(
                "{} case {} (id {}): rewrite returned {:#x}, lift returned {:#x}",
                instance.address, case, id, returned, expected
            ));
        }
    }
    None
}

macro_rules! instance_test {
    ($name:ident, $index:expr) => {
        #[test]
        fn $name() {
            let _guard = LOCK.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
            let instance = &INSTANCES[$index];
            assert_eq!(TASK_FLAG_BITS[$index].bit, instance.bit, "{}", instance.address);
            let seed = 0x5851_F42D_4C95_7F2D ^ ($index as u64 + 1);
            if let Some(message) = first_mismatch(instance, lifted, seed) {
                panic!("lifted method differs from the rewrite: {message}");
            }
            assert!(
                first_mismatch(instance, wrong_flags_offset, seed).is_some(),
                "wrong version (flags offset moved) was not caught for {}",
                instance.address
            );
            assert!(
                first_mismatch(instance, wrong_bit_one_higher, seed).is_some(),
                "wrong version (bit one higher) was not caught for {}",
                instance.address
            );
            assert!(
                first_mismatch(instance, wrong_unmasked, seed).is_some(),
                "wrong version (bit not masked) was not caught for {}",
                instance.address
            );
        }
    };
}

instance_test!(t_fn_00c50df0, 0);
instance_test!(t_fn_00c50e10, 1);
instance_test!(t_fn_00c50e30, 2);
instance_test!(t_fn_00c50e50, 3);