//! Differential test of the lifted slot-record store against the verified
//! rewrites of its family.
//!
//! Each rewrite selects a slot record through the object's selector byte and
//! one of eight selector-table globals, then stores the low bytes of its
//! argument into one field of that record. The lifted method is
//! `SlotStore::store` in `lf-core`. For each instance, CASES generated objects
//! are built in memory with generated selector-table globals. The rewrite is
//! called with the object's address; the lifted method runs on a copy of the
//! same bytes. The whole object must match afterwards, and the rewrite must
//! leave the table globals unchanged, since it only reads them.
//!
//! The record offsets stay small because the generated table words are small;
//! that keeps every write inside the object buffer.
//!
//! Wrong versions, each of which every instance must catch: the selector mask
//! cut to two bits, the record shift reduced to four, the field offset moved
//! by one byte, and the width changed to the other width.

#![cfg(target_arch = "x86")]

#[path = "support/instances_gen.rs"]
mod instances;

use std::sync::Mutex;

use instances::{INSTANCES, Instance};
use lf_core::slot_store::{SELECTOR_OFFSET, SLOT_STORES, SlotStore, TABLE_LEN};
use lf_recstoredif::rt::{SLOT_VAS, plant, read_back};

/// Generated cases per instance.
const CASES: u32 = 1000;

/// Bytes in one generated object: far more than any record the table words allow.
const OBJECT_BYTES: usize = 0x400;

/// One lock across the whole test program: the rewrites share globals.
static LOCK: Mutex<()> = Mutex::new(());

/// A deterministic generator (xorshift64), seeded per instance.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.0 = x;
        x
    }

    fn word(&mut self) -> u32 {
        self.next() as u32
    }

    /// Fills `bytes` with generated bytes, eight at a time.
    fn fill(&mut self, bytes: &mut [u8]) {
        for chunk in bytes.chunks_mut(8) {
            let word = self.next().to_le_bytes();
            chunk.copy_from_slice(&word[..chunk.len()]);
        }
    }
}

/// A candidate: the same contract as the lifted method, for one instance.
type Candidate = fn(SlotStore, &mut [u8], &[u32; TABLE_LEN], u32);

fn lifted(store: SlotStore, object: &mut [u8], table: &[u32; TABLE_LEN], value: u32) {
    store.store(object, table, value);
}

/// The store written with a selector mask and record shift given explicitly.
fn model(
    object: &mut [u8],
    table: &[u32; TABLE_LEN],
    value: u32,
    store: SlotStore,
    mask: u8,
    shift: u32,
) {
    let selector = usize::from(object[SELECTOR_OFFSET] & mask);
    let record = table[selector].wrapping_shl(shift);
    let field = record.wrapping_add(store.field_offset) as usize;
    let bytes = value.to_le_bytes();
    object[field..field + store.width].copy_from_slice(&bytes[..store.width]);
}

fn wrong_selector_mask(store: SlotStore, object: &mut [u8], table: &[u32; TABLE_LEN], value: u32) {
    model(object, table, value, store, 0x03, 5);
}

fn wrong_shift_four(store: SlotStore, object: &mut [u8], table: &[u32; TABLE_LEN], value: u32) {
    model(object, table, value, store, 0x07, 4);
}

fn wrong_field_moved(store: SlotStore, object: &mut [u8], table: &[u32; TABLE_LEN], value: u32) {
    SlotStore::new(store.field_offset + 1, store.width).store(object, table, value);
}

fn wrong_width_changed(store: SlotStore, object: &mut [u8], table: &[u32; TABLE_LEN], value: u32) {
    SlotStore::new(store.field_offset, 3 - store.width).store(object, table, value);
}

/// The first mismatch of a candidate against the instance's rewrite, if any.
fn first_mismatch(instance: &Instance, store: SlotStore, candidate: Candidate, seed: u64) -> Option<String> {
    let mut rng = Rng(seed);
    for case in 0..CASES {
        let mut object = vec![0u8; OBJECT_BYTES];
        rng.fill(&mut object);
        let mut table = [0u32; TABLE_LEN];
        for (slot, word) in table.iter_mut().enumerate() {
            *word = rng.word() % 16;
            plant(SLOT_VAS[slot], *word);
        }
        let value = rng.word();

        let mut lifted_object = object.clone();
        let this = object.as_ptr() as usize as u32;
        (instance.call)(this, value);

        for (slot, &va) in SLOT_VAS.iter().enumerate() {
            if read_back(va) != table[slot] {
                return Some(format!(
                    "{} case {}: the rewrite changed the table global {:#x}, which it must only read",
                    instance.address, case, va
                ));
            }
        }
        candidate(store, &mut lifted_object, &table, value);
        if object != lifted_object {
            let at = (0..OBJECT_BYTES).find(|&b| object[b] != lifted_object[b]).unwrap_or(0);
            return Some(format!(
                "{} case {}: object byte {:#x} is {:#x} in the rewrite and {:#x} in the lift",
                instance.address, case, at, object[at], lifted_object[at]
            ));
        }
    }
    None
}

macro_rules! instance_test {
    ($name:ident, $index:expr) => {
        #[test]
        fn $name() {
            let _guard = LOCK.lock().unwrap_or_else(|poisoned| poisoned.into_inner());
            let instance = &INSTANCES[$index];
            let store = SLOT_STORES[$index];
            assert_eq!(store.field_offset, instance.field_offset, "{}", instance.address);
            assert_eq!(store.width, instance.width, "{}", instance.address);
            let seed = 0x5851_F42D_4C95_7F2D ^ ($index as u64 + 1);
            if let Some(message) = first_mismatch(instance, store, lifted, seed) {
                panic!("lifted method differs from the rewrite: {message}");
            }
            assert!(
                first_mismatch(instance, store, wrong_selector_mask, seed).is_some(),
                "wrong version (selector mask) was not caught for {}",
                instance.address
            );
            assert!(
                first_mismatch(instance, store, wrong_shift_four, seed).is_some(),
                "wrong version (shift four) was not caught for {}",
                instance.address
            );
            assert!(
                first_mismatch(instance, store, wrong_field_moved, seed).is_some(),
                "wrong version (field moved) was not caught for {}",
                instance.address
            );
            assert!(
                first_mismatch(instance, store, wrong_width_changed, seed).is_some(),
                "wrong version (width changed) was not caught for {}",
                instance.address
            );
        }
    };
}

instance_test!(t_fn_00897fb0, 0);
instance_test!(t_fn_00898060, 1);
instance_test!(t_fn_008980d0, 2);
instance_test!(t_fn_00897ef0, 3);
