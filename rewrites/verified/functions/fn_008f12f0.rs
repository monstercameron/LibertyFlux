//! Rewrite of the input binding-table initializer: resets six sub-tables,
//! then registers several hundred key/button bindings through one shared
//! register routine. Straight-line table runs with a few mode/capability
//! gates; every call and store below was extracted mechanically and
//! cross-checked by two independent analyses (see the lane report).
use lf_checker_rt::{callee_thiscall, export, global, relocated};

/// Register one binding row in sub-table `this`. Arguments are in push
/// order (a0 pushed first); the call reverses them into C order.
#[inline(always)]
fn reg(this: u32, a0: u32, a1: u32, a2: u32, a3: u32) {
    let _answer: u32 = callee_thiscall!(1, u32, this, a3, a2, a1, a0);
}
/// Reset one sub-table (clears its live entries).
#[inline(always)]
fn reset(this: u32) {
    let _answer: u32 = callee_thiscall!(2, u32, this);
}
/// Look up the capability record for this object.
#[inline(always)]
fn lookup(this: u32) -> u32 {
    callee_thiscall!(3, u32, this)
}
/// Three capability probes over a record pointer; nonzero means capable.
#[inline(always)]
fn probe_a(p: u32) -> u8 { callee_thiscall!(4, u8, p) }
#[inline(always)]
fn probe_b(p: u32) -> u8 { callee_thiscall!(5, u8, p) }
#[inline(always)]
fn probe_c(p: u32) -> u8 { callee_thiscall!(6, u8, p) }
#[inline(always)]
fn r32(addr: u32) -> u32 { unsafe { (addr as *const u32).read() } }
#[inline(always)]
fn w32(addr: u32, v: u32) { unsafe { (addr as *mut u32).write(v) } }
#[inline(always)]
fn g32(file_va: u32) -> u32 { unsafe { global::<u32>(file_va).read() } }
#[inline(always)]
fn g8(file_va: u32) -> u8 { unsafe { global::<u8>(file_va).read() } }
/// One register call: sub-table offset, whether arg0 is the live index
/// (else -1), target-field offset, flags, kind.
struct Row { this: u32, idx0: bool, a1: u32, a2: u32, a3: u32 }
#[inline(always)]
fn run(obj: u32, idx: u32, rows: &[Row]) {
    for r in rows {
        reg(obj.wrapping_add(r.this), if r.idx0 { idx } else { 0xFFFF_FFFF }, obj.wrapping_add(r.a1), r.a2, r.a3);
    }
}
