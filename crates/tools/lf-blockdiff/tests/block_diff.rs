//! Differential test of the lifted word-block copy against the verified
//! rewrites of its family.
//!
//! Each rewrite copies three or four consecutive words between an object and
//! the buffer its caller passes, and returns zero, the buffer's address or the
//! last word of the run. The lifted method is `WordBlockCopy::run` in
//! `lf-core`. For each instance, CASES generated objects and buffers are built
//! in memory. The rewrite is called with the object's address and the buffer's
//! address; the lifted method runs on copies of the same bytes. Both object
//! and buffer must match byte for byte afterwards, and the return must match:
//! a buffer return is compared with the buffer's address, which the lift does
//! not hold and the test rebuilds.
//!
//! Wrong versions, each of which every instance must catch: the object offset
//! shifted by one word, the last word of the run left out, the direction
//! reversed, and the return replaced by the first word of the run.

#![cfg(target_arch = "x86")]

#[path = "support/instances_gen.rs"]
mod instances;

use instances::{INSTANCES, Instance};
use lf_core::word_block::{BLOCK_COPIES, CopyOutcome, CopyReturn, WordBlockCopy};

/// Generated cases per instance.
const CASES: u32 = 1000;

/// Bytes in one generated object. The largest run starts at the highest
/// object offset of the family and is three words long.
const OBJECT_BYTES: usize = 0x1480;

/// Bytes in one generated buffer. Four words is the longest run.
const BUFFER_BYTES: usize = 16;

/// A deterministic generator (xorshift64), seeded per instance.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.0 = x;
        x
    }

    /// Fills `bytes` with generated bytes, eight at a time.
    fn fill(&mut self, bytes: &mut [u8]) {
        for chunk in bytes.chunks_mut(8) {
            let word = self.next().to_le_bytes();
            chunk.copy_from_slice(&word[..chunk.len()]);
        }
    }
}

/// A candidate: the same contract as the lifted method, for one instance.
type Candidate = fn(WordBlockCopy, &mut [u8], &mut [u8]) -> CopyOutcome;

fn lifted(copy: WordBlockCopy, object: &mut [u8], buffer: &mut [u8]) -> CopyOutcome {
    copy.run(object, buffer)
}

fn wrong_offset_shifted(copy: WordBlockCopy, object: &mut [u8], buffer: &mut [u8]) -> CopyOutcome {
    let mut shifted = copy;
    shifted.object_offset += 4;
    shifted.run(object, buffer)
}

fn wrong_last_word_left_out(
    copy: WordBlockCopy,
    object: &mut [u8],
    buffer: &mut [u8],
) -> CopyOutcome {
    let mut shorter = copy;
    shorter.words -= 1;
    shorter.run(object, buffer)
}

fn wrong_direction_reversed(
    copy: WordBlockCopy,
    object: &mut [u8],
    buffer: &mut [u8],
) -> CopyOutcome {
    let mut reversed = copy;
    reversed.direction = match copy.direction {
        lf_core::word_block::CopyDirection::FromObject => {
            lf_core::word_block::CopyDirection::IntoObject
        }
        lf_core::word_block::CopyDirection::IntoObject => {
            lf_core::word_block::CopyDirection::FromObject
        }
    };
    reversed.run(object, buffer)
}

fn wrong_return_first_word(
    copy: WordBlockCopy,
    object: &mut [u8],
    buffer: &mut [u8],
) -> CopyOutcome {
    let _ = copy.run(object, buffer);
    let mut bytes = [0u8; 4];
    bytes.copy_from_slice(&buffer[..4]);
    CopyOutcome::Word(u32::from_le_bytes(bytes))
}

/// The value the original returns, given the outcome and the buffer's address.
fn returned_value(outcome: CopyOutcome, buffer_address: u32) -> u32 {
    match outcome {
        CopyOutcome::Null => 0,
        CopyOutcome::Buffer => buffer_address,
        CopyOutcome::Word(word) => word,
    }
}

/// The first mismatch of a candidate against the instance's rewrite, if any.
fn first_mismatch(
    instance: &Instance,
    copy: WordBlockCopy,
    candidate: Candidate,
    seed: u64,
) -> Option<String> {
    let mut rng = Rng(seed);
    for case in 0..CASES {
        let mut object = vec![0u8; OBJECT_BYTES];
        rng.fill(&mut object);
        let mut buffer = vec![0u8; BUFFER_BYTES];
        rng.fill(&mut buffer);

        let mut lifted_object = object.clone();
        let mut lifted_buffer = buffer.clone();

        let this = object.as_ptr() as usize as u32;
        let buffer_address = buffer.as_ptr() as usize as u32;
        let returned = (instance.call)(this, buffer_address);

        let outcome = candidate(copy, &mut lifted_object, &mut lifted_buffer);
        let expected = returned_value(outcome, buffer_address);
        if object != lifted_object {
            let at = (0..OBJECT_BYTES)
                .find(|&b| object[b] != lifted_object[b])
                .unwrap_or(0);
            return Some(format!(
                "{} case {}: object byte {:#x} is {:#x} in the rewrite and {:#x} in the lift",
                instance.name, case, at, object[at], lifted_object[at]
            ));
        }
        if buffer != lifted_buffer {
            let at = (0..BUFFER_BYTES)
                .find(|&b| buffer[b] != lifted_buffer[b])
                .unwrap_or(0);
            return Some(format!(
                "{} case {}: buffer byte {:#x} is {:#x} in the rewrite and {:#x} in the lift",
                instance.name, case, at, buffer[at], lifted_buffer[at]
            ));
        }
        if returned != expected {
            return Some(format!(
                "{} case {}: rewrite returned {:#x}, lift returned {:#x}",
                instance.name, case, returned, expected
            ));
        }
    }
    None
}

/// The lifted copy of instance `index`, as the lifted table has it.
fn copy_of(index: usize) -> WordBlockCopy {
    BLOCK_COPIES[index]
}

macro_rules! instance_test {
    ($name:ident, $index:expr) => {
        #[test]
        fn $name() {
            let instance = &INSTANCES[$index];
            let copy = copy_of($index);
            assert_eq!(copy.direction, instance.direction, "{}", instance.name);
            assert_eq!(
                copy.object_offset, instance.object_offset,
                "{}",
                instance.name
            );
            assert_eq!(copy.words, instance.words, "{}", instance.name);
            assert_eq!(copy.returns, instance.returns, "{}", instance.name);
            let seed = 0x5851_F42D_4C95_7F2D ^ ($index as u64 + 1);
            if let Some(message) = first_mismatch(instance, copy, lifted, seed) {
                panic!("lifted method differs from the rewrite: {message}");
            }
            assert!(
                first_mismatch(instance, copy, wrong_offset_shifted, seed).is_some(),
                "wrong version (offset shifted) was not caught for {}",
                instance.name
            );
            assert!(
                first_mismatch(instance, copy, wrong_last_word_left_out, seed).is_some(),
                "wrong version (last word left out) was not caught for {}",
                instance.name
            );
            assert!(
                first_mismatch(instance, copy, wrong_direction_reversed, seed).is_some(),
                "wrong version (direction reversed) was not caught for {}",
                instance.name
            );
            assert!(
                first_mismatch(instance, copy, wrong_return_first_word, seed).is_some(),
                "wrong version (first word returned) was not caught for {}",
                instance.name
            );
        }
    };
}

#[test]
fn the_lifted_table_has_one_entry_per_instance() {
    assert_eq!(BLOCK_COPIES.len(), INSTANCES.len());
    assert!(BLOCK_COPIES.iter().any(|c| c.returns == CopyReturn::Null));
}

